/// Create a conversational checkout payment link for ChatGPT actions or web UI
pub fn generate_checkout_url(price_id: &str, user_ref: Option<&str>) -> String {
    let user_param = user_ref.unwrap_or("anon");
    let live = crate::stripe::is_live_mode();

    // Check for direct Stripe Payment Link URL overrides per plan (checking live vs test)
    let plan_override = if price_id.contains("solo") {
        if live {
            std::env::var("STRIPE_SOLO_CHECKOUT_URL_LIVE").or_else(|_| std::env::var("STRIPE_SOLO_CHECKOUT_URL")).ok()
        } else {
            std::env::var("STRIPE_SOLO_CHECKOUT_URL_TEST").or_else(|_| std::env::var("STRIPE_SOLO_CHECKOUT_URL")).ok()
        }
    } else if price_id.contains("business") {
        if live {
            std::env::var("STRIPE_BUSINESS_CHECKOUT_URL_LIVE").or_else(|_| std::env::var("STRIPE_BUSINESS_CHECKOUT_URL")).ok()
        } else {
            std::env::var("STRIPE_BUSINESS_CHECKOUT_URL_TEST").or_else(|_| std::env::var("STRIPE_BUSINESS_CHECKOUT_URL")).ok()
        }
    } else if price_id.contains("agency") {
        if live {
            std::env::var("STRIPE_AGENCY_CHECKOUT_URL_LIVE").or_else(|_| std::env::var("STRIPE_AGENCY_CHECKOUT_URL")).ok()
        } else {
            std::env::var("STRIPE_AGENCY_CHECKOUT_URL_TEST").or_else(|_| std::env::var("STRIPE_AGENCY_CHECKOUT_URL")).ok()
        }
    } else if price_id.contains("single") || price_id.contains("pass") {
        if live {
            std::env::var("STRIPE_PASS_24H_CHECKOUT_URL_LIVE").or_else(|_| std::env::var("STRIPE_PASS_24H_CHECKOUT_URL")).ok()
        } else {
            std::env::var("STRIPE_PASS_24H_CHECKOUT_URL_TEST").or_else(|_| std::env::var("STRIPE_PASS_24H_CHECKOUT_URL")).ok()
        }
    } else if price_id.contains("pack") {
        if live {
            std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL_LIVE").or_else(|_| std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL")).ok()
        } else {
            std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL_TEST").or_else(|_| std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL")).ok()
        }
    } else {
        None
    };

    if let Some(link) = plan_override {
        let sep = if link.contains('?') { '&' } else { '?' };
        return format!("{}{}client_reference_id={}", link, sep, user_param);
    }

    let base = if live {
        std::env::var("STRIPE_CHECKOUT_BASE_URL_LIVE")
            .or_else(|_| std::env::var("STRIPE_CHECKOUT_BASE_URL"))
            .unwrap_or_else(|_| "https://buy.stripe.com/live_pressmark".to_string())
    } else {
        std::env::var("STRIPE_CHECKOUT_BASE_URL_TEST")
            .or_else(|_| std::env::var("STRIPE_CHECKOUT_BASE_URL"))
            .unwrap_or_else(|_| "https://buy.stripe.com/test_pressmark".to_string())
    };

    if base.contains('?') {
        format!("{}&client_reference_id={}", base, user_param)
    } else {
        format!("{}_{}?client_reference_id={}", base, price_id, user_param)
    }
}

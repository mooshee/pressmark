/// Create a conversational checkout payment link for ChatGPT actions or web UI
pub fn generate_checkout_url(price_id: &str, user_ref: Option<&str>) -> String {
    let user_param = user_ref.unwrap_or("anon");
    let live = crate::stripe::is_live_mode();
    let (
        solo_price_id,
        business_price_id,
        agency_price_id,
        single_pass_price_id,
        starter_pack_price_id,
    ) = resolve_price_ids(live);

    // Check for direct Stripe Payment Link URL overrides per plan (matching plan ID, price ID, or keyword)
    let plan_override = if price_id == "plan_solo" || price_id.contains("solo") || price_id == solo_price_id {
        if live {
            std::env::var("STRIPE_SOLO_CHECKOUT_URL_LIVE")
                .or_else(|_| std::env::var("STRIPE_SOLO_CHECKOUT_URL"))
                .ok()
                .or_else(|| Some("https://buy.stripe.com/4gM3cu8jk4Psd095197wA04".to_string()))
        } else {
            std::env::var("STRIPE_SOLO_CHECKOUT_URL_TEST")
                .or_else(|_| std::env::var("STRIPE_SOLO_CHECKOUT_URL"))
                .ok()
        }
    } else if price_id == "plan_business" || price_id.contains("business") || price_id == business_price_id {
        if live {
            std::env::var("STRIPE_BUSINESS_CHECKOUT_URL_LIVE")
                .or_else(|_| std::env::var("STRIPE_BUSINESS_CHECKOUT_URL"))
                .ok()
                .or_else(|| Some("https://buy.stripe.com/4gM7sK6bcgya7FPdxF7wA00".to_string()))
        } else {
            std::env::var("STRIPE_BUSINESS_CHECKOUT_URL_TEST")
                .or_else(|_| std::env::var("STRIPE_BUSINESS_CHECKOUT_URL"))
                .ok()
        }
    } else if price_id == "plan_agency" || price_id.contains("agency") || price_id == agency_price_id {
        if live {
            std::env::var("STRIPE_AGENCY_CHECKOUT_URL_LIVE")
                .or_else(|_| std::env::var("STRIPE_AGENCY_CHECKOUT_URL"))
                .ok()
                .or_else(|| Some("https://buy.stripe.com/fZu9ASeHIbdQ0dn1OX7wA02".to_string()))
        } else {
            std::env::var("STRIPE_AGENCY_CHECKOUT_URL_TEST")
                .or_else(|_| std::env::var("STRIPE_AGENCY_CHECKOUT_URL"))
                .ok()
        }
    } else if price_id == "pass_single_unlock" || price_id.contains("single") || price_id.contains("pass") || price_id == single_pass_price_id {
        if live {
            std::env::var("STRIPE_PASS_24H_CHECKOUT_URL_LIVE")
                .or_else(|_| std::env::var("STRIPE_PASS_24H_CHECKOUT_URL"))
                .ok()
                .or_else(|| Some("https://buy.stripe.com/28E28qbvw6XA2lvfFN7wA03".to_string()))
        } else {
            std::env::var("STRIPE_PASS_24H_CHECKOUT_URL_TEST")
                .or_else(|_| std::env::var("STRIPE_PASS_24H_CHECKOUT_URL"))
                .ok()
        }
    } else if price_id == "pass_starter_pack" || price_id.contains("pack") || price_id == starter_pack_price_id {
        if live {
            std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL_LIVE")
                .or_else(|_| std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL"))
                .ok()
                .or_else(|| Some("https://buy.stripe.com/6oU00i2Z081Ed09gJR7wA01".to_string()))
        } else {
            std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL_TEST")
                .or_else(|_| std::env::var("STRIPE_CREDIT_PACK_CHECKOUT_URL"))
                .ok()
        }
    } else {
        None
    };

    if let Some(link) = plan_override {
        let sep = if link.contains('?') { '&' } else { '?' };
        return format!("{}{}client_reference_id={}", link, sep, user_param);
    }

    let base = if live {
        std::env::var("STRIPE_CHECKOUT_BASE_URL_LIVE")
            .or_else(|_| std::env::var("STRIPE_CHECKOUT_BASE_URL"))
            .unwrap_or_else(|_| "https://buy.stripe.com/live_pressmark".to_string())
    } else {
        std::env::var("STRIPE_CHECKOUT_BASE_URL_TEST")
            .or_else(|_| std::env::var("STRIPE_CHECKOUT_BASE_URL"))
            .unwrap_or_else(|_| "https://buy.stripe.com/test_pressmark".to_string())
    };

    if base.contains('?') {
        format!("{}&client_reference_id={}", base, user_param)
    } else {
        format!("{}_{}?client_reference_id={}", base, price_id, user_param)
    }
}

pub fn get_state_lease_profile(query: &str) -> Option<&'static StateLeaseProfile> {
    let trimmed = query.trim();
    if trimmed.is_empty() {
        return None;
    }
    let normalized = trimmed.to_ascii_lowercase().replace('_', "-");
    if normalized == "dc"
        || normalized == "d.c."
        || normalized == "washington-dc"
        || normalized == "washington-d.c."
        || normalized == "district-of-columbia"
    {
        return STATE_LEASE_PROFILES.iter().find(|p| p.code == "DC");
    }

    for profile in STATE_LEASE_PROFILES {
        if profile.code.eq_ignore_ascii_case(trimmed)
            || profile.name.eq_ignore_ascii_case(trimmed)
            || profile.slug == normalized
            || profile.name.to_ascii_lowercase().replace(' ', "-") == normalized
        {
            return Some(profile);
        }
    }
    None
}


/// Attempts to infer a 2-letter US state code from a postal address string (e.g. "Chattanooga, TN 37402").
/// Scans from the end of the address backward so street directionals/names ("123 NE 45th St", "8500 LA Cienega Blvd",
/// "500 CO Rd 12", "100 MT Vernon Ave", "300 DE Kalb Ave") are never misidentified as state codes.
pub fn infer_state_from_address(address: &str) -> Option<&'static StateLeaseProfile> {
    for line in address.lines().rev() {
        let has_comma = line.contains(',');
        let search_segment = match line.find(',') {
            Some(idx) => &line[idx + 1..],
            None => line,
        };
        let mut tokens: Vec<&str> = search_segment
            .split(|c: char| c.is_whitespace() || c == ',' || c == ';')
            .filter(|t| !t.is_empty())
            .collect();

        // Strip trailing country token ("USA", "US") if present
        if let Some(&last) = tokens.last() {
            let trimmed = last.trim_matches(|c: char| !c.is_ascii_alphabetic());
            if trimmed.eq_ignore_ascii_case("usa") {
                tokens.pop();
            }
        }

        let last_is_zip = tokens.last().is_some_and(|t| {
            let digits = t.trim_matches(|c: char| !c.is_ascii_alphanumeric() && c != '-');
            digits.len() >= 5 && digits.as_bytes()[..5].iter().all(|b| b.is_ascii_digit())
        });
        let starts_with_street_num = line
            .trim_start()
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_digit());

        for (rev_idx, token) in tokens.iter().rev().enumerate() {
            // If the line had no comma, only inspect the final two tokens (state or state + ZIP)
            if !has_comma && rev_idx > 1 {
                break;
            }
            // Guard street suffix like "100 Oak CT" when there is no comma and no ZIP code
            if !has_comma && !last_is_zip && starts_with_street_num && rev_idx == 0 {
                break;
            }
            let clean = token.trim_matches(|c: char| !c.is_ascii_alphabetic());
            if clean.len() == 2 && clean.chars().all(|c| c.is_ascii_alphabetic()) {
                let allow_case_insensitive = has_comma || (last_is_zip && rev_idx == 1);
                if allow_case_insensitive || clean.chars().all(|c| c.is_ascii_uppercase()) {
                    if let Some(p) = get_state_lease_profile(clean) {
                        return Some(p);
                    }
                }
            }
        }
    }

    // Fallback: match full state name (longest name first so "West Virginia" precedes "Virginia")
    let lower = address.to_ascii_lowercase();
    let mut states_by_len: Vec<&'static StateLeaseProfile> = STATE_LEASE_PROFILES.iter().collect();
    states_by_len.sort_by(|a, b| b.name.len().cmp(&a.name.len()));
    for sp in states_by_len {
        let name_lower = sp.name.to_ascii_lowercase();
        if lower.contains(&name_lower) {
            return Some(sp);
        }
    }

    None
}


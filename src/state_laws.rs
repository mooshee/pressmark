use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ConspicuousClause {
    pub point_size: u8,
    pub bold: bool,
    pub uppercase: bool,
    pub underlined: bool,
    pub title: &'static str,
    pub citation: &'static str,
    pub verbatim_text: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct StandaloneAttachment {
    pub title: &'static str,
    pub citation: &'static str,
    pub requires_separate_initials: bool,
    pub body: &'static str,
}

